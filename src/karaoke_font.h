inline const uint8_t* karaoke_glyph(char32_t cp) {
    // sorted by code point: binary search
    int lo = 0, hi = static_cast<int>(sizeof(kKaraokeFont) / sizeof(kKaraokeFont[0])) - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) / 2;
        if (kKaraokeFont[mid].cp == cp) return kKaraokeFont[mid].rows;
        if (kKaraokeFont[mid].cp < cp) lo = mid + 1; else hi = mid - 1;
    }
    return nullptr;
}

