#!/usr/bin/env python3
"""Generates src/script_tables.inc: Chinese characters that tell Japanese from Chinese text.
  kJapaneseOnly: in the Japanese character set (JIS X 0208 / 0213) but in neither the simplified (GB 2312) nor the traditional (Big5) one
                 (桜 楽 変 沢 畑 峠 ...)
  kChineseOnly:  in the simplified or traditional set but not in the Japanese one (们 这 乐 伦 个 ...)
Only Python's standard codecs are used."""
import sys

def decode_set(codec, lead_lo, lead_hi):
    out = set()
    for b1 in range(lead_lo, lead_hi + 1):
        for b2 in range(0x40, 0xFF):
            try:
                ch = bytes([b1, b2]).decode(codec)
            except Exception:
                continue
            if len(ch) == 1 and 0x3400 <= ord(ch) <= 0x9FFF:
                out.add(ord(ch))
    return out

jp = decode_set('euc_jis_2004', 0xA1, 0xFE)
# the 3-byte JIS X 0212 plane is not needed: the common Japanese characters are in the first two planes
gb = decode_set('gb2312', 0xA1, 0xF7)
big5 = decode_set('big5', 0xA1, 0xF9)
jp_only = sorted(jp - gb - big5)
zh_only = sorted((gb | big5) - jp)
out = sys.argv[1] if len(sys.argv) > 1 else "src/script_tables.inc"
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_script_tables.py (Python's JIS / GB 2312 / Big5 codecs). Do not edit.\n")
    for name, arr in (("kJapaneseOnly", jp_only), ("kChineseOnly", zh_only)):
        f.write("static const char32_t %s[] = {" % name)
        for i, v in enumerate(arr):
            f.write(("\n" if i % 16 == 0 else "") + "0x%X," % v)
        f.write("};\n")
print(len(jp_only), "Japanese-only,", len(zh_only), "Chinese-only")
