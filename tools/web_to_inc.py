#!/usr/bin/env python3
"""remote_app/web/index.html  ->  src/remote_page.inc

The page of the remote app (served by Mousiki's own web server, see src/remote_server.h) is a plain HTML file in
remote_app/web/. This script compiles it into src/remote_page.inc, which src/remote_server.cpp includes:

    static const char* const kRemotePage[] = { R"WEB(...)WEB", ..., nullptr };

The page is cut into chunks of about 8000 bytes (at line ends) because some compilers limit the length of one string
literal. Run it after every change of the page:

    python3 tools/web_to_inc.py [input.html] [output.inc]
"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "remote_app", "web", "index.html")
dst = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, "src", "remote_page.inc")

with open(src, "rb") as f:
    raw = f.read()
if raw.startswith(b"\xef\xbb\xbf"):
    raw = raw[3:]
text = raw.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n")
if ')WEB"' in text:
    sys.exit('the page contains the sequence )WEB" which ends a raw string literal')

chunks, cur, size = [], [], 0
for line in text.split("\n"):
    cur.append(line)
    size += len(line.encode("utf-8")) + 1
    if size >= 8000:
        chunks.append("\n".join(cur) + "\n")
        cur, size = [], 0
if cur:
    chunks.append("\n".join(cur))

with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by tools/web_to_inc.py from remote_app/web/index.html -- edit the page, then run the script.\n")
    f.write("static const char* const kRemotePage[] = {\n")
    for c in chunks:
        f.write('R"WEB(' + c + ')WEB",\n')
    f.write("nullptr};\n")
print("%s: %d bytes in %d chunks -> %s" % (os.path.relpath(src, root), len(raw), len(chunks), dst))
