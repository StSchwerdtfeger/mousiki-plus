#!/usr/bin/env python3
"""Generates src/pinyin_table.inc (the Mandarin reading of every common CJK character) from the pypinyin package (MIT licence,
https://github.com/mozillazg/python-pinyin). Run once when the table should be refreshed:  pip install pypinyin && python3 tools/gen_pinyin_inc.py"""
import sys
from pypinyin.pinyin_dict import pinyin_dict

LO, HI = 0x3400, 0x9FFF
OVERRIDE = {"长": "cháng", "地": "de", "着": "zhe", "得": "de"}   # the reading that is far more common in lyrics / titles
syl, ids, table = [], {}, []
for cp in range(LO, HI + 1):
    ch = chr(cp)
    r = OVERRIDE.get(ch) or (pinyin_dict.get(cp, "").split(",")[0])
    if not r:
        table.append(0)
        continue
    if r not in ids:
        ids[r] = len(syl) + 1
        syl.append(r)
    table.append(ids[r])
out = sys.argv[1] if len(sys.argv) > 1 else "src/pinyin_table.inc"
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_pinyin_inc.py from pypinyin (MIT licence). Do not edit.\n")
    f.write("static const int kPinyinFirst = 0x%X, kPinyinLast = 0x%X;\n" % (LO, HI))
    f.write("static const char* const kPinyinSyllables[] = {\"\"")
    for s in syl:
        f.write(",\"%s\"" % s)
    f.write("};\nstatic const unsigned short kPinyinIndex[] = {")
    for i, v in enumerate(table):
        f.write(("\n" if i % 24 == 0 else "") + str(v) + ",")
    f.write("};\n")
print(len(syl), "syllables,", sum(1 for t in table if t), "characters")
